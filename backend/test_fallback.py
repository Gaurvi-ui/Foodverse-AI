
import os
from unittest.mock import patch

from app.services.ai import analyze, GeminiTemporaryError

# Supply temporary test credentials.
# These are NOT real API keys.
with patch.dict(os.environ, {"GROQ_API_KEY": "test-groq-key"}):

    # Simulate Gemini being unavailable.
    with patch(
        "app.services.ai._analyze_gemini",
        side_effect=GeminiTemporaryError("Simulated Gemini 503 error")
    ) as gemini_mock:

        # Simulate a successful Groq response.
        with patch(
            "app.services.ai._analyze_groq",
            return_value={
                "recipes": [
                    {
                        "name": "Test Paneer Rice",
                        "description": "Test recipe generated by mocked Groq."
                    }
                ]
            }
        ) as groq_mock:

            result = analyze(
                kind="recipes",
                prompt="Generate a vegetarian paneer recipe.",
                provider="gemini",
                api_key="test-gemini-key",
                demo=False
            )

            print("\n========== FALLBACK TEST RESULT ==========")
            print("Provider used:", result["provider_used"])
            print("Fallback used:", result["fallback_used"])
            print("Fallback reason:", result["fallback_reason"])
            print("Demo mode:", result["demo"])
            print("Recipe:", result["recipes"][0]["name"])

            assert result["provider_used"] == "groq"
            assert result["fallback_used"] is True
            assert result["demo"] is False
            assert gemini_mock.call_count == 1
            assert groq_mock.call_count == 1

            print("\nSUCCESS: Gemini-to-Groq fallback logic works!")
